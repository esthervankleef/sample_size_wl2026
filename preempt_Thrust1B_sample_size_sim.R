##########################################################################
# UK THRUST 1B POWER / SAMPLE-SIZE ANALYSIS
# Design-stage event-yield approximation for R0-within
#
# PURPOSE
# -------
# Estimate how many UK OVG participants are likely to need baseline
# screening, and how many pARG-positive participants need to enter the
# controlled antibiotic challenge, to generate sufficient longitudinal
# plasmid-host acquisition information for Thrust 1B.
#
# SCIENTIFIC FRAMEWORK
# --------------------
# The target biological quantity, R0-within, is NOT defined as the number
# of observed events per participant.
#
# Mechanistically, within-gut plasmid spread is expected to depend on:
#
#   beta        = effective in-vivo transfer/acquisition rate
#   D           = donor abundance
#   S           = susceptible-recipient abundance
#   gamma       = plasmid-host loss rate
#   structure   = effective spatial/ecological opportunity for transfer
#   detection   = probability that a true acquisition is resolved
#
# A design-stage branching approximation for the final estimand is:
#
#   R0-within = beta * S_eff * structure_factor / gamma
#
# where S_eff represents susceptible-recipient abundance under the
# specified antibiotic/ecological state.
#
# WHAT THIS POWER SIMULATION DOES
# -------------------------------
# This script does NOT directly estimate beta, D, S, gamma, or R0-within.
#
# Instead, for sample-size planning, the biological acquisition process
#
#   beta x D x S x ecological opportunity
#
# is collapsed into:
#
#   events_per_positive
#
# defined as the expected number of true new plasmid-host acquisition
# events generated by one pARG-positive challenge participant over the
# full observation window.
#
# Thus:
#
#   screened participants
#       -> baseline pARG-positive participants
#       -> pARG-positive challenge participants
#       -> true acquisition events
#       -> detected acquisition events
#       -> approximate information / precision
#
# True acquisition events are simulated using a Poisson approximation,
# and each true event is subsequently observed with probability
# detection_probability.
#
# PRECISION APPROXIMATION
# -----------------------
# For design purposes, this script uses:
#
#   relative_precision ~= 1.96 / sqrt(number of detected events)
#
# as a simple event-count information approximation.
#
# Therefore, the variable currently labelled probability_R0_precision_50
# should be interpreted as the probability of obtaining enough detected
# acquisition events to satisfy the design-stage 50% precision proxy.
#
# It is NOT yet the simulated confidence-interval precision of an
# estimated R0-within.
#
# INTERPRETATION
# --------------
# This analysis is intended to answer:
#
#   1. How many randomly selected participants need to be screened?
#   2. How many pARG-positive participants are likely to be available
#      for controlled antibiotic challenge?
#   3. Under plausible acquisition and detection rates, how many resolved
#      plasmid-host acquisition events are likely to be observed?
#   4. Is that event yield sufficient to support the planned mechanistic
#      analysis?
#
# FINAL LEAP ANALYSIS
# -------------------
# This is a DESIGN-STAGE POWER / FEASIBILITY SIMULATION, not the final
# Wellcome Leap estimator.
#
# The final longitudinal analysis will estimate within-gut plasmid
# transmission mechanistically from the observed plasmid-host data,
# including acquisition, susceptible-cell opportunity, antibiotic state,
# persistence/loss, and relevant participant-level/ecological structure.
#
# The final R0-within estimate will therefore be derived from the
# pre-specified longitudinal mechanistic model rather than from
# events_per_positive or the simple event-count precision approximation
# used here.
##########################################################################

